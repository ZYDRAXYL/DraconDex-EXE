#!/usr/bin/env node
// Procress 29 part 5 — vendor the open-source icon sets the icon picker
// offers beside the app's own icons. Offline like d3/konva: one generated
// script per set in electron/vendor/icons/, loaded the first time a set is
// shown (electron/src/renderer/core/icon-sets.js), plus the set's LICENSE.
//
//   npm pack lucide-static @phosphor-icons/core @tabler/icons   (anywhere)
//   tar -xzf each into its own folder, then:
//   node tools/icon-sets.mjs --lucide <dir>/package --phosphor <dir>/package --tabler <dir>/package
//
// Each icon keeps only its inner SVG markup and a few search words; the
// set's shared <svg> attributes are written once. Re-run to update a set —
// the version it came from is in the generated file's header.
import { readFileSync, readdirSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'electron', 'vendor', 'icons');
const arg = (k) => { const i = process.argv.indexOf(`--${k}`); return i > 0 ? process.argv[i + 1] : null; };

// The inner markup of an SVG file, minified: no comments, no newlines, no
// invisible 'stroke="none"' frame paths (Tabler draws one in every icon).
function inner(svg) {
  return svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
    .replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>/g, '')
    .replace(/\s*\n\s*/g, '').replace(/\s+\/>/g, '/>').trim();
}
const words = (list) => [...new Set((list || []).flatMap((w) => String(w).toLowerCase().split(/[\s-]+/)))].slice(0, 8).join(' ');

function write(set, meta, icons) {
  mkdirSync(out, { recursive: true });
  const body = Object.entries(icons).sort(([a], [b]) => a.localeCompare(b))
    .map(([name, { svg, tags }]) => `${JSON.stringify(name)}:[${JSON.stringify(svg)},${JSON.stringify(tags)}]`).join(',\n');
  writeFileSync(path.join(out, `${set}.js`), `'use strict';
// GENERATED by tools/icon-sets.mjs — do not edit. ${meta.label} ${meta.version}, ${meta.license} (LICENSE-${set}).
// name: [inner SVG markup, search words]
iconSetAdd(${JSON.stringify(set)}, ${JSON.stringify({ label: meta.label, viewBox: meta.viewBox, attrs: meta.attrs })}, {
${body}
});
`);
  console.log(`${set}: ${Object.keys(icons).length} icons`);
}

const pkgVersion = (dir) => JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8')).version;

const lucide = arg('lucide');
if (lucide) {
  const tags = JSON.parse(readFileSync(path.join(lucide, 'tags.json'), 'utf8'));
  const icons = {};
  for (const f of readdirSync(path.join(lucide, 'icons')).filter((n) => n.endsWith('.svg'))) {
    const name = f.slice(0, -4);
    icons[name] = { svg: inner(readFileSync(path.join(lucide, 'icons', f), 'utf8')), tags: words(tags[name]) };
  }
  write('lucide', { label: 'Lucide', version: pkgVersion(lucide), license: 'ISC', viewBox: '0 0 24 24',
    attrs: 'fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"' }, icons);
  copyFileSync(path.join(lucide, 'LICENSE'), path.join(out, 'LICENSE-lucide'));
}

const phosphor = arg('phosphor');
if (phosphor) {
  const { icons: list } = await import(path.join(phosphor, 'dist', 'index.mjs'));
  const tags = Object.fromEntries(list.map((i) => [i.name, i.tags]));
  const icons = {};
  for (const f of readdirSync(path.join(phosphor, 'assets', 'regular')).filter((n) => n.endsWith('.svg'))) {
    const name = f.slice(0, -4);
    icons[name] = { svg: inner(readFileSync(path.join(phosphor, 'assets', 'regular', f), 'utf8')), tags: words(tags[name]) };
  }
  write('phosphor', { label: 'Phosphor', version: pkgVersion(phosphor), license: 'MIT', viewBox: '0 0 256 256', attrs: 'fill="currentColor"' }, icons);
  copyFileSync(path.join(phosphor, 'LICENSE'), path.join(out, 'LICENSE-phosphor'));
}

const tabler = arg('tabler');
if (tabler) {
  const meta = JSON.parse(readFileSync(path.join(tabler, 'icons.json'), 'utf8'));
  const icons = {};
  for (const f of readdirSync(path.join(tabler, 'icons', 'outline')).filter((n) => n.endsWith('.svg'))) {
    const name = f.slice(0, -4);
    icons[name] = { svg: inner(readFileSync(path.join(tabler, 'icons', 'outline', f), 'utf8')), tags: words(meta[name]?.tags) };
  }
  write('tabler', { label: 'Tabler', version: pkgVersion(tabler), license: 'MIT', viewBox: '0 0 24 24',
    attrs: 'fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"' }, icons);
  copyFileSync(path.join(tabler, 'LICENSE'), path.join(out, 'LICENSE-tabler'));
}
